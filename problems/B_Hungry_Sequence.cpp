#include <iostream>
#include <vector>

using namespace std;
using ll = long long;

void SOLVE()
{
    ll n;
    cin >> n;

    const int N = 1e7;

    vector<bool> prime(N + 1, true);

    prime[0] = prime[1] = false;

    for (int i = 2; i * i <= N; i++)
    {
        if (prime[i])
        {
            for (int j = i * i; j <= N; j += i)
            {
                prime[j] = false;
            }
        }
    }

    int cnt = 0;

    for (int i = 2; i <= N && cnt < n; i++)
    {
        if (prime[i])
        {
            cout << i << " ";
            cnt++;
        }
    }
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(NULL);

    SOLVE();
}